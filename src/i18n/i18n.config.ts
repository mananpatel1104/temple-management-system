/**
 * Resolves a dot-path translation key (e.g. "common.loading") for a given
 * language, falling back to English if the key or language is missing.
 */
export function resolveTranslation(
  language: SupportedLanguage,
  key: TranslationKey,
): string {
  const path = key.split('.');
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  let node: any = translationResources[language] ?? translationResources.en;
  for (const segment of path) {
    node = node?.[segment];
    if (node === undefined) {
      // eslint-disable-next-line @typescript-eslint/no-explicit-any
      let fallback: any = translationResources.en;
      for (const seg of path) fallback = fallback?.[seg];
      return fallback ?? key;
    }
  }
  return typeof node === 'string' ? node : key;
}
